#!/usr/bin/env python3
"""Save the serial CSV of a firmware/bench sketch under the loop (card) id.

    python3 scripts/bench_log.py --port /dev/tty.usbmodem* --card C005 --name bts-bench
        -> data/logs/<YYYY-MM-DD>_C005_bts-bench.csv, echoed to the screen, Ctrl-C closes the file cleanly.
    python3 scripts/bench_log.py --fake --card C000 --name demo
        -> 3 s of generated CSV (no hardware, no pyserial needed) to test the script and the naming.

While logging, anything you type + Enter is sent to the board (so `s 0.3`, `limit 1.0`, `?` work from here)
and is written to the file as `# > <command>` so the log shows what was sent when.

Everything the board prints is saved as is: one CSV header, rows, and `# ` message lines
(`# DEADMAN`, `# WARN …`). Read it back with  pandas.read_csv(path, comment='#').

pyserial is imported only when a real port is used:  pip install pyserial
"""
from __future__ import annotations

import argparse
import datetime as dt
import glob
import os
import re
import sys
import threading
import time
from typing import Iterator, Optional

DEFAULT_OUTDIR = os.path.join("data", "logs")
CARD_RE = re.compile(r"^C\d{3}$")
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")


def parse_args(argv: Optional[list] = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="bench_log.py",
        description="Log the CSV of a firmware/bench sketch to data/logs/<date>_<card>_<name>.csv",
        epilog="File naming rule: tests/data/README.md. Card ids come from the AR-Mini Board (C001, C002, …).",
    )
    p.add_argument("--port", help="serial port, e.g. /dev/tty.usbmodem1101 (a glob like /dev/tty.usb* is allowed if it matches one port)")
    p.add_argument("--baud", type=int, default=115200, help="baud rate (default 115200)")
    p.add_argument("--card", required=True, help="card id on the AR-Mini Board, e.g. C005")
    p.add_argument("--name", required=True, help="short slug, lowercase letters/digits/dashes, e.g. bts-bench")
    p.add_argument("--outdir", default=DEFAULT_OUTDIR, help=f"output folder (default {DEFAULT_OUTDIR})")
    p.add_argument("--date", help="override the date part (YYYY-MM-DD); default today")
    p.add_argument("--fake", action="store_true", help="generate fake CSV instead of reading a port (for testing)")
    p.add_argument("--fake-seconds", type=float, default=3.0, help="length of the fake stream (default 3 s)")
    p.add_argument("--quiet", action="store_true", help="do not echo rows to the screen (messages are still shown)")
    a = p.parse_args(argv)

    if not CARD_RE.match(a.card):
        p.error(f"--card must look like C005 (got {a.card!r})")
    if not NAME_RE.match(a.name):
        p.error(f"--name must be lowercase letters, digits and dashes (got {a.name!r})")
    if a.date:
        try:
            dt.date.fromisoformat(a.date)
        except ValueError:
            p.error(f"--date must be YYYY-MM-DD (got {a.date!r})")
    if not a.fake and not a.port:
        p.error("either --port or --fake is required")
    return a


def output_path(outdir: str, card: str, name: str, date: Optional[str]) -> str:
    """data/logs/<date>_<card>_<name>.csv; never overwrite — add _2, _3, … if it exists."""
    day = date or dt.date.today().isoformat()
    base = os.path.join(outdir, f"{day}_{card}_{name}")
    path = base + ".csv"
    n = 2
    while os.path.exists(path):
        path = f"{base}_{n}.csv"
        n += 1
    return path


def resolve_port(pattern: str) -> str:
    matches = sorted(glob.glob(pattern)) if any(ch in pattern for ch in "*?[") else [pattern]
    if len(matches) == 0:
        sys.exit(f"bench_log: no serial port matches {pattern!r}")
    if len(matches) > 1:
        sys.exit("bench_log: several ports match, pick one:\n  " + "\n  ".join(matches))
    return matches[0]


# ---------------------------------------------------------------------------- sources
def fake_lines(seconds: float, realtime: bool = True) -> Iterator[str]:
    """Imitates the bts7960 sketch: banner, header, 10 Hz rows, a ramp, a DEADMAN."""
    yield "# AR-Mini bench · fake · build (none)"
    yield "# this stream is generated by scripts/bench_log.py --fake"
    yield "t_ms,cmd,pwm_r,pwm_l,is_r_mV,is_l_mV,kill"
    rows = max(1, int(round(seconds * 10)))
    t0 = 1000
    cmd = 0.3
    pwm = 0.0
    for i in range(rows):
        if i == rows // 2:
            yield "# DEADMAN"
            cmd = 0.0
            pwm = 0.0
        pwm = min(pwm + 0.05, cmd) if cmd > 0 else 0.0
        yield f"{t0 + i * 100},{cmd:.3f},{int(round(pwm * 255))},0,-1,-1,0"
        if realtime:
            time.sleep(0.1)


class SerialSource:
    def __init__(self, port: str, baud: int) -> None:
        try:
            import serial  # type: ignore
        except ImportError:
            sys.exit("bench_log: pyserial is not installed — run `pip install pyserial` (or use --fake to test)")
        self._serial = serial.Serial(port, baud, timeout=0.2)

    def lines(self) -> Iterator[str]:
        buf = b""
        while True:
            chunk = self._serial.read(256)
            if not chunk:
                continue
            buf += chunk
            while b"\n" in buf:
                raw, buf = buf.split(b"\n", 1)
                yield raw.rstrip(b"\r").decode("utf-8", errors="replace")

    def write_line(self, text: str) -> None:
        self._serial.write((text + "\n").encode("utf-8"))

    def close(self) -> None:
        self._serial.close()


def stdin_forwarder(source: SerialSource, log, lock: threading.Lock) -> None:
    """Daemon thread: lines typed here go to the board and into the log as `# > cmd`."""
    for line in sys.stdin:
        cmd = line.strip()
        if not cmd:
            continue
        source.write_line(cmd)
        with lock:
            log.write(f"# > {cmd}\n")
            log.flush()


# ---------------------------------------------------------------------------- main
def main(argv: Optional[list] = None) -> int:
    a = parse_args(argv)
    os.makedirs(a.outdir, exist_ok=True)
    path = output_path(a.outdir, a.card, a.name, a.date)

    source: Optional[SerialSource] = None
    if a.fake:
        lines = fake_lines(a.fake_seconds)
        where = "fake"
    else:
        port = resolve_port(a.port)
        source = SerialSource(port, a.baud)
        lines = source.lines()
        where = f"{port} @ {a.baud}"

    started = dt.datetime.now()
    rows = msgs = 0
    header: Optional[str] = None
    lock = threading.Lock()
    print(f"bench_log: {where} -> {path}   (Ctrl-C to stop; type a command + Enter to send it)", file=sys.stderr)

    with open(path, "w", encoding="utf-8", newline="\n") as log:
        log.write(f"# bench_log {started.isoformat(timespec='seconds')} card={a.card} name={a.name} source={where}\n")
        if source is not None:
            threading.Thread(target=stdin_forwarder, args=(source, log, lock), daemon=True).start()
        try:
            for line in lines:
                with lock:
                    log.write(line + "\n")
                    log.flush()
                if line.startswith("#"):
                    msgs += 1
                    print(line, file=sys.stderr)
                elif header is None:
                    header = line
                    print(line)
                else:
                    rows += 1
                    if not a.quiet:
                        print(line)
        except KeyboardInterrupt:
            print("\nbench_log: Ctrl-C", file=sys.stderr)
        finally:
            if source is not None:
                source.close()

    seconds = (dt.datetime.now() - started).total_seconds()
    print(f"bench_log: saved {path}  ({rows} rows, {msgs} message lines, {seconds:.1f} s"
          f"{'' if header else ', NO CSV HEADER SEEN'})", file=sys.stderr)
    return 0 if header else 2


if __name__ == "__main__":
    sys.exit(main())
