#!/usr/bin/env python3
"""AR-Mini C085 · turn out/results.jsonl into results/results.md and the drag-vs-speed plot."""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
RHO, NU, G, L = 998.2, 1.0e-6, 9.81, 0.610
S_HULL = 0.0869          # m², wetted area of one hull at 23 mm draft (outline perimeter × draft + bottom)

rows = [json.loads(l) for l in open(os.path.join(HERE, "out", "results.jsonl")) if l.strip()]
os.makedirs(RES, exist_ok=True)


def ittc(U):
    return 0.075 / (math.log10(U * L / NU) - 2) ** 2


def boat(r):   # drag of the whole configuration: single = 2 × half hull, pair = 2 × one hull
    return 2 * r["drag_N"], 2 * r["drag_pressure_N"], 2 * r["drag_viscous_N"]


main = {(r["mode"], r["speed"]): r for r in rows if r["case"].startswith(("single_U", "pair_U"))}
speeds = sorted({k[1] for k in main})
md = ["# C085 · hull drag from OpenFOAM (generated by report.py)", "",
      "Double-body RANS (simpleFoam, k-omega SST), fresh water 20 °C, draft 23 mm (2.5 kg). **No waves in the model.**",
      "`one hull` = a single hull alone. `catamaran` = both hulls 350 mm apart (centre to centre). Forces in newtons.", "",
      "| speed, m/s | Froude | one hull: drag | friction | pressure | ITTC-57 friction | catamaran: drag | catamaran / (2 × one hull) | tow power, W | y+ mean |",
      "|---|---|---|---|---|---|---|---|---|---|"]
tab = []
for U in speeds:
    s, p = main.get(("single", U)), main.get(("pair", U))
    if not s or not p:
        continue
    ds, dps, dvs = boat(s); dp, _, _ = boat(p)
    fr = U / math.sqrt(G * L)
    fi = 0.5 * RHO * U * U * S_HULL * ittc(U)
    tab.append((U, fr, ds, dvs, dps, fi, dp))
    md.append(f"| {U:.1f} | {fr:.2f} | {ds:.3f} | {dvs:.3f} | {dps:.3f} | {fi:.3f} | {dp:.3f} | {dp / (2 * ds):.2f} | {dp * U:.3f} | {p['yplus_mean']:.0f} |")
md += ["", "Tow power = catamaran drag × speed (what the water takes; the thruster needs more).", ""]
mesh = [r for r in rows if r["case"].startswith("mesh_")] + [main[("single", 0.6)]] if ("single", 0.6) in main else []
if mesh:
    mesh.sort(key=lambda r: r["cells"])
    md += ["## Mesh check, one hull at 0.6 m/s", "", "| base cell, mm | cells | drag of one hull, N | friction | pressure |", "|---|---|---|---|---|"]
    for r in mesh:
        d, dp_, dv = boat(r)
        md.append(f"| {r['base_m'] * 1000:.0f} | {r['cells']} | {d:.4f} | {dv:.4f} | {dp_:.4f} |")
    a, b = boat(mesh[-2])[0], boat(mesh[-1])[0]
    md += ["", f"Two finest meshes differ by {abs(a - b) / b * 100:.1f} %.", ""]
open(os.path.join(RES, "results.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
fig, ax = plt.subplots(figsize=(9, 5.5), dpi=150)
U = [t[0] for t in tab]
ax.plot(U, [t[6] for t in tab], "o-", label="catamaran (both hulls), CFD double-body")
ax.plot(U, [2 * t[2] for t in tab], "s--", label="2 × one hull alone, CFD")
ax.plot(U, [2 * t[5] for t in tab], ":", color="0.4", label="2 × ITTC-57 friction line (flat plate, same wetted area)")
ax.axvspan(math.sqrt(G * L) * 0.3, max(U) + 0.05, color="orange", alpha=0.15, label="Froude > 0.3: wave drag matters, not in this model")
ax.set_xlabel("speed, m/s"); ax.set_ylabel("drag, N"); ax.grid(alpha=0.3); ax.legend(fontsize=8)
ax.set_xlim(0, max(U) + 0.05); ax.set_ylim(0)
ax.set_title("AR-Mini hull drag vs speed (C085) · OpenFOAM, no waves, draft 23 mm at 2.5 kg")
fig.savefig(os.path.join(RES, "C085_drag_vs_speed.png"), bbox_inches="tight")
