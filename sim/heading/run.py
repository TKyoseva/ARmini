#!/usr/bin/env python3
"""AR-Mini C077 · build step.cpp against the firmware's Heading.h, run it, plot the step response.

  python3 sim/heading/run.py        # needs a C++ compiler (c++), matplotlib

The controller in the plot is the same header the firmware will use; only the boat is simulated.
"""
import csv
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.join(HERE, "..", "..", "firmware", "armini", "lib", "core")
OUT = os.path.join(HERE, "out")            # binary + CSV, gitignored
RES = os.path.join(HERE, "results")


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(RES, exist_ok=True)
    exe = os.path.join(OUT, "step")
    subprocess.run(["c++", "-std=c++11", "-Wall", "-Wextra", "-I", CORE, os.path.join(HERE, "step.cpp"), "-o", exe], check=True)
    text = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    open(os.path.join(OUT, "step.csv"), "w").write(text)
    runs = {}
    for row in csv.DictReader(text.splitlines()):
        runs.setdefault(row["model"], []).append((float(row["t_s"]), float(row["target_deg"]),
                                                  float(row["heading_deg"]), float(row["turn"])))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, (a, b) = plt.subplots(2, 1, figsize=(10, 7), dpi=150, sharex=True, gridspec_kw={"height_ratios": [3, 2]})
    lines = ["# C077 · heading hold step response (generated by run.py)", "",
             "10° step at t = 2 s, constant push of 5 °/s from t = 0, 50 Hz loop, gains from Heading.h.", "",
             "| boat model (ASSUMED) | peak overshoot, ° | worst error after 10 s from the step, ° | error at 40 s, ° |", "|---|---|---|---|"]
    ok = True
    for name, rows in runs.items():
        t = [r[0] for r in rows]
        a.plot(t, [r[2] for r in rows], label=name)
        b.plot(t, [r[3] for r in rows])
        over = max(r[2] - r[1] for r in rows if r[0] >= 2.0)
        late = max(abs(r[2] - r[1]) for r in rows if r[0] >= 12.0)
        ok &= late < 5.0
        lines.append(f"| {name} | {over:.1f} | {late:.2f} | {abs(rows[-1][2] - rows[-1][1]):.2f} |")
    t = [r[0] for r in next(iter(runs.values()))]
    tg = [r[1] for r in next(iter(runs.values()))]
    a.plot(t, tg, "k--", lw=1, label="target")
    a.fill_between(t, [v - 5 for v in tg], [v + 5 for v in tg], color="0.85", label="±5° band")
    a.axvline(12.0, color="0.5", lw=0.8, ls=":")
    a.set_ylabel("heading, °"); a.legend(fontsize=8, loc="lower right"); a.grid(alpha=0.3)
    a.set_title("AR-Mini heading hold in simulation (C077): PI controller from Heading.h, simulated boat")
    b.set_ylabel("turn command (−1…+1)\nrudder = 1500 + 333 · turn µs"); b.set_xlabel("time, s"); b.grid(alpha=0.3)
    fig.savefig(os.path.join(RES, "C077_heading_step.png"), bbox_inches="tight")
    lines += ["", f"Pass criterion (inside ±5° 10 s after the step, every model): {'PASS' if ok else 'FAIL'}.", ""]
    open(os.path.join(RES, "results.md"), "w").write("\n".join(lines))
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
